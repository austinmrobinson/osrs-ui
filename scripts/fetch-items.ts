// Demo-only item icons for the recipe screens, from the OSRS Wiki (CC BY-NC-SA 3.0).
// Downloads to reference/items (gitignored) and writes site/demo-data/items.tsx via the same
// pixel-exact converter. Not part of the registry.
import fs from "node:fs";
import path from "node:path";
import { readPng, toSvg } from "./lib/pixels";

const ROOT = path.resolve(import.meta.dirname, "..");
const DIR = path.join(ROOT, "reference/items");
const OUT = path.join(ROOT, "site/demo-data/items.tsx");
const UA = "osrs-ui-docs/0.1 (+https://github.com/austinmrobinson/osrs-ui)";

const ITEMS = [
  "Abyssal whip", "Dragon defender", "Fire cape", "Amulet of glory(6)", "Barrows gloves", "Dragon boots",
  "Helm of neitiznot", "Fighter torso", "Dragon platelegs", "Berserker ring (i)", "Rune arrow",
  "Dragon scimitar", "Rune platebody", "Shark", "Prayer potion(4)", "Super combat potion(4)",
  "Saradomin brew(4)", "Super restore(4)", "Stamina potion(4)", "Coins 10000", "Nature rune", "Law rune",
  "Fire rune", "Air rune", "Water rune", "Death rune", "Blood rune", "Logs", "Oak logs", "Willow logs",
  "Yew logs", "Magic logs", "Raw lobster", "Lobster", "Raw shark", "Bones", "Dragon bones",
  "Rune pickaxe", "Dragon axe", "Tinderbox", "Knife", "Hammer", "Ring of dueling(8)", "Games necklace(8)",
  "Bronze bar", "Iron ore", "Coal", "Gold bar", "Uncut diamond", "Cooked karambwan", "Anglerfish",
  "Twisted bow", "Toxic blowpipe", "Spade", "Clue scroll (elite)", "Grimy ranarr weed", "Grimy snapdragon",
  "Grimy torstol", "Grimy toadflax", "Grimy avantoe", "Ranarr weed", "Snapdragon", "Torstol", "Weeds", "Supercompost",
];

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const pascal = (s: string) => slug(s).replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase()).replace(/^(\d)/, "_$1");

fs.mkdirSync(DIR, { recursive: true });
const rows: string[] = [];
const map: string[] = [];
for (const name of ITEMS) {
  const file = path.join(DIR, `${slug(name)}.png`);
  if (!fs.existsSync(file)) {
    const url = `https://oldschool.runescape.wiki/images/${encodeURIComponent(name.replace(/ /g, "_"))}.png`;
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) { console.warn(`skip ${name}: ${res.status}`); continue; }
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  const bmp = readPng(file);
  const inner = toSvg(bmp).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "").replace(/fill-opacity=/g, "fillOpacity=");
  rows.push(`export const ${pascal(name)}Item = createSprite("${pascal(name)}Item", ${bmp.width}, ${bmp.height}, <>${inner}</>);`);
  map.push(`  ${JSON.stringify(slug(name))}: { name: ${JSON.stringify(name.replace(/ 10000$/, ""))}, Icon: ${pascal(name)}Item },`);
}
fs.writeFileSync(
  OUT,
  `// Generated by scripts/fetch-items.ts — demo-only item icons from the OSRS Wiki (CC BY-NC-SA 3.0).
import { createSprite } from "@/lib/sprite";

${rows.join("\n")}

export const items = {
${map.join("\n")}
} as const;

export type ItemId = keyof typeof items;
`,
);
console.log(`${rows.length}/${ITEMS.length} items -> site/demo-data/items.tsx`);
