// Skill SVGs -> React icon components (registry/osrs/icons/skill-icons.tsx)
import fs from "node:fs";
import path from "node:path";
import type { ManifestEntry } from "./build-assets";

const ROOT = path.resolve(import.meta.dirname, "..");
const ASSETS = path.join(ROOT, "registry/osrs/assets");
const OUT = path.join(ROOT, "registry/osrs/icons/skill-icons.tsx");
const manifest: ManifestEntry[] = JSON.parse(fs.readFileSync(path.join(ASSETS, "manifest.json"), "utf8"));

const pascal = (s: string) => s.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());

const skills = manifest.filter((m) => m.group === "skill");
const icons = skills.map((m) => {
  const svg = fs.readFileSync(path.join(ASSETS, m.file), "utf8");
  const inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/fill-opacity=/g, "fillOpacity=")
    .replace(/"\/>/g, '" />');
  return { name: m.name, comp: `${pascal(m.name)}Icon`, w: m.width, h: m.height, inner };
});

const src = `// Generated by scripts/build-icons.ts — do not edit.
// Pixel-exact vector recreations of the Old School RuneScape skill icons.
import * as React from "react";

export type OsrsIconProps = Omit<React.SVGProps<SVGSVGElement>, "width" | "height"> & {
  /** Integer multiple of the native sprite size. Defaults to the theme's --osrs-px scale. */
  scale?: number;
  /** Explicit pixel width (height follows aspect ratio). Overrides \`scale\`. */
  size?: number;
  title?: string;
};

function createIcon(displayName: string, w: number, h: number, children: React.ReactNode) {
  const Icon = React.forwardRef<SVGSVGElement, OsrsIconProps>(({ scale, size, title, style, className, ...props }, ref) => {
    const width = size ?? (scale ? w * scale : undefined);
    const height = size ? (size * h) / w : scale ? h * scale : undefined;
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        viewBox={\`0 0 \${w} \${h}\`}
        width={width}
        height={height}
        shapeRendering="crispEdges"
        role={title ? "img" : undefined}
        aria-hidden={title ? undefined : true}
        className={["osrs-icon", className].filter(Boolean).join(" ")}
        style={width === undefined ? { width: \`calc(\${w} * var(--osrs-px, 1px))\`, height: \`calc(\${h} * var(--osrs-px, 1px))\`, ...style } : style}
        {...props}
      >
        {title ? <title>{title}</title> : null}
        {children}
      </svg>
    );
  });
  Icon.displayName = displayName;
  return Icon;
}

${icons.map((i) => `export const ${i.comp} = createIcon("${i.comp}", ${i.w}, ${i.h}, <>${i.inner}</>);`).join("\n")}

export const skillIcons = {
${icons.map((i) => `  ${i.name}: ${i.comp},`).join("\n")}
} as const;

export type SkillName = keyof typeof skillIcons;

export function SkillIcon({ skill, ...props }: OsrsIconProps & { skill: SkillName }) {
  const Icon = skillIcons[skill];
  return <Icon {...props} />;
}
`;
fs.writeFileSync(OUT, src);
console.log(`wrote ${icons.length} icons -> ${path.relative(ROOT, OUT)}`);
