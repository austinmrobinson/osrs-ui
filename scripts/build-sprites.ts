// Asset SVGs -> generated React sprite modules, one per group (registry/osrs/ui/<group>-sprites.tsx).
import fs from "node:fs";
import path from "node:path";
import type { ManifestEntry } from "./build-assets";

const ROOT = path.resolve(import.meta.dirname, "..");
const ASSETS = path.join(ROOT, "registry/osrs/assets");
const UI = path.join(ROOT, "registry/osrs/ui");
const manifest: ManifestEntry[] = JSON.parse(fs.readFileSync(path.join(ASSETS, "manifest.json"), "utf8"));

/** group -> [file name, component suffix, map name] */
export const MODULES: Record<string, [string, string, string]> = {
  skill: ["skill-icons", "Icon", "skillIcons"],
  prayer: ["prayer-sprites", "Prayer", "prayerSprites"],
  orb: ["orb-sprites", "Orb", "orbSprites"],
  panel: ["panel-sprites", "Panel", "panelSprites"],
  ge: ["ge-sprites", "Ge", "geSprites"],
  chevron: ["chevron-sprites", "Chevron", "chevronSprites"],
  glyph: ["glyph-sprites", "Glyph2", "glyphSprites"],
  equipment: ["equipment-sprites", "Equipment", "equipmentSprites"],
  stats: ["stats-sprites", "Stats", "statsSprites"],
  combat: ["combat-sprites", "Combat", "combatSprites"],
  bank: ["bank-sprites", "Bank", "bankSprites"],
  tab: ["tab-sprites", "Tab", "tabSprites"],
  icon: ["icon-sprites", "Glyph", "iconSprites"],
  chatbox: ["chatbox-sprites", "Chatbox", "chatboxSprites"],
  option: ["option-sprites", "Option", "optionSprites"],
};

const pascal = (s: string) => s.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase()).replace(/^(\d)/, "_$1");
const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

for (const [group, [file, suffix, mapName]] of Object.entries(MODULES)) {
  const items = manifest.filter((m) => m.group === group);
  const sprites = items.map((m) => {
    const inner = fs
      .readFileSync(path.join(ASSETS, m.file), "utf8")
      .replace(/^<svg[^>]*>/, "")
      .replace(/<\/svg>$/, "")
      .replace(/fill-opacity=/g, "fillOpacity=")
      .replace(/"\/>/g, '" />');
    return { key: camel(m.name), comp: `${pascal(m.name)}${suffix}`, w: m.width, h: m.height, inner };
  });
  const src = `// Generated by scripts/build-sprites.ts — do not edit.
// Pixel-exact vector recreations of Old School RuneScape ${group} sprites.
import { createSprite } from "@/lib/sprite";

${sprites.map((s) => `export const ${s.comp} = createSprite("${s.comp}", ${s.w}, ${s.h}, <>${s.inner}</>);`).join("\n")}

export const ${mapName} = {
${sprites.map((s) => `  ${JSON.stringify(s.key)}: ${s.comp},`).join("\n")}
} as const;

export type ${pascal(group)}SpriteName = keyof typeof ${mapName};
`;
  const extra =
    group === "skill"
      ? `
export type OsrsIconProps = import("@/lib/sprite").SpriteProps;

export function SkillIcon({ skill, ...props }: OsrsIconProps & { skill: SkillSpriteName }) {
  const Icon = skillIcons[skill];
  return <Icon {...props} />;
}
`
      : "";
  fs.writeFileSync(path.join(UI, `${file}.tsx`), src + extra);
  console.log(`${file}.tsx: ${sprites.length} sprites`);
}
