// theme/base.css + manifest.json + SVGs -> registry/osrs/theme/osrs.css
// Every asset is inlined as a data URI so the stylesheet is self-contained
// (works in the registry, in Blume's preview iframes, and in any app).
import fs from "node:fs";
import path from "node:path";
import type { ManifestEntry } from "./build-assets";

const ROOT = path.resolve(import.meta.dirname, "..");
const ASSETS = path.join(ROOT, "registry/osrs/assets");
const THEME = path.join(ROOT, "registry/osrs/theme");
const OUT = path.join(THEME, "osrs.css");
const manifest: ManifestEntry[] = JSON.parse(fs.readFileSync(path.join(ASSETS, "manifest.json"), "utf8"));

// Big multi-colour textures are left out of the stylesheet; they are still downloadable assets.
const SKIP_CSS = new Set<string>();
const CSS_GROUPS = new Set(["frame", "texture", "control"]);

const dataUri = (svg: string) =>
  `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E")}")`;

/** The sprite mirrored across its diagonal (x and y swapped), so a vertical piece reads horizontally. */
const transpose = (svg: string, w: number, h: number) =>
  svg
    .replace(/<svg([^>]*)>/, (_, attrs: string) =>
      `<svg${attrs.replace(/width="\d+"/, `width="${h}"`).replace(/height="\d+"/, `height="${w}"`).replace(/viewBox="[^"]*"/, `viewBox="0 0 ${h} ${w}"`)}><g transform="matrix(0 1 1 0 0 0)">`,
    )
    .replace(/<\/svg>\s*$/, "</g></svg>");

const px = (n: number) => `calc(${n} * var(--osrs-px))`;
const varName = (m: ManifestEntry) => `--osrs-${m.group}-${m.name}`;

const vars: string[] = [];
const rules: string[] = [];

for (const m of manifest) {
  if (SKIP_CSS.has(m.name) || !CSS_GROUPS.has(m.group)) continue;
  const svg = fs.readFileSync(path.join(ASSETS, m.file), "utf8");
  vars.push(`  ${varName(m)}: ${dataUri(svg)};`);
  // The game only draws the scrollbar thumb upright; horizontal scrollbars use the same pieces
  // transposed (top cap -> left cap), as --osrs-control-scroll-thumb-*-x.
  if (m.group === "control" && m.name.startsWith("scroll-thumb-")) vars.push(`  ${varName(m)}-x: ${dataUri(transpose(svg, m.width, m.height))};`);

  if (m.group === "frame" && m.slice) {
    const [t, r, b, l] = m.slice;
    const [bt, br, bb, bl] = m.border!;
    // The frame is painted by ::before so its slice size never dictates layout;
    // --osrs-frame-pad exposes the visible border thickness for padding.
    rules.push(`.osrs-frame-${m.name} {
  --osrs-frame-image: var(${varName(m)});
  --osrs-frame-slice: ${t} ${r} ${b} ${l};
  --osrs-frame-width: ${px(t)} ${px(r)} ${px(b)} ${px(l)};
  --osrs-frame-pad: ${px(bt)} ${px(br)} ${px(bb)} ${px(bl)};
}`);
  }
  if (m.group === "texture") {
    rules.push(`.osrs-texture-${m.name} {
  background-image: var(${varName(m)});
  background-size: ${px(m.width)} ${px(m.height)};
  background-repeat: repeat;
}`);
  }
  if (m.group === "control") {
    rules.push(`.osrs-${m.group}-${m.name} { --osrs-sprite: var(${varName(m)}); --osrs-sprite-w: ${m.width}; --osrs-sprite-h: ${m.height}; }`);
  }
}

// Inline the RuneStar fonts (CC0) so the stylesheet needs no static files.
const baseRaw = fs.readFileSync(path.join(THEME, "base.css"), "utf8");
// @font-face must stay top-level; everything else goes in the components layer so
// Tailwind utilities (hidden, flex, …) always win over library defaults, like stock shadcn.
const fontFaces = (baseRaw.match(/@font-face \{[^}]*\}\n?/g) ?? []).join("");
const base = baseRaw.replace(/@font-face \{[^}]*\}\n?/g, "");
const fonts = fontFaces
  .replace(/url\("\/fonts\/osrs\/([\w-]+\.(ttf|otf))"\)/g, (_, f: string, ext: string) => {
    const b64 = fs.readFileSync(path.join(ROOT, "registry/osrs/fonts", f)).toString("base64");
    return `url("data:font/${ext};base64,${b64}")`;
  });
fs.writeFileSync(
  OUT,
  `/* Generated by scripts/build-css.ts from theme/base.css — edit that file instead. */\n${fonts}\n` +
    `/* ---------- Generated asset variables ---------- */\n:root {\n${vars.join("\n")}\n}\n\n` +
    `@layer components {\n${base}\n${rules.join("\n")}\n}\n`,
);
console.log(`wrote ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);

// The docs site's theme.css = library stylesheet + site skin (Blume reads ./theme.css).
fs.writeFileSync(
  path.join(ROOT, "theme.css"),
  fs.readFileSync(OUT, "utf8") + "\n" + fs.readFileSync(path.join(ROOT, "site/site.css"), "utf8"),
);

// Preview frames get the library plus a few frame-only rules.
const examplesCss = fs.readFileSync(OUT, "utf8") + "\n" + fs.readFileSync(path.join(ROOT, "site/examples.css"), "utf8");
fs.writeFileSync(path.join(ROOT, "site/examples.generated.css"), examplesCss);

// Dev convenience: Blume copies examples.css only at startup; refresh its copy so HMR picks it up.
const blumeCopy = path.join(ROOT, ".blume/src/generated/examples.css");
if (fs.existsSync(blumeCopy)) {
  const current = fs.readFileSync(blumeCopy, "utf8");
  const marker = "/* Generated by scripts/build-css.ts";
  const at = current.indexOf(marker);
  if (at >= 0) fs.writeFileSync(blumeCopy, current.slice(0, at) + examplesCss);
}
