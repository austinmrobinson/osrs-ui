// theme/base.css + manifest.json + SVGs -> registry/osrs/theme/osrs.css
// Every asset is inlined as a data URI so the stylesheet is self-contained
// (works in the registry, in Blume's preview iframes, and in any app).
import fs from "node:fs";
import path from "node:path";
import type { ManifestEntry } from "./build-assets";

const ROOT = path.resolve(import.meta.dirname, "..");
const ASSETS = path.join(ROOT, "registry/osrs/assets");
const THEME = path.join(ROOT, "registry/osrs/theme");
const OUT = path.join(THEME, "osrs.css");
const manifest: ManifestEntry[] = JSON.parse(fs.readFileSync(path.join(ASSETS, "manifest.json"), "utf8"));

// Big multi-colour textures are left out of the stylesheet; they are still downloadable assets.
const SKIP_CSS = new Set(["side-panel"]);

const dataUri = (svg: string) =>
  `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E")}")`;

const px = (n: number) => `calc(${n} * var(--osrs-px))`;
const varName = (m: ManifestEntry) => `--osrs-${m.group}-${m.name}`;

const vars: string[] = [];
const rules: string[] = [];

for (const m of manifest) {
  if (SKIP_CSS.has(m.name) || m.group === "skill") continue;
  const svg = fs.readFileSync(path.join(ASSETS, m.file), "utf8");
  vars.push(`  ${varName(m)}: ${dataUri(svg)};`);

  if (m.group === "frame" && m.slice) {
    const [t, r, b, l] = m.slice;
    const [bt, br, bb, bl] = m.border!;
    // The frame is painted by ::before so its slice size never dictates layout;
    // --osrs-frame-pad exposes the visible border thickness for padding.
    rules.push(`.osrs-frame-${m.name} {
  --osrs-frame-image: var(${varName(m)});
  --osrs-frame-slice: ${t} ${r} ${b} ${l};
  --osrs-frame-width: ${px(t)} ${px(r)} ${px(b)} ${px(l)};
  --osrs-frame-pad: ${px(bt)} ${px(br)} ${px(bb)} ${px(bl)};
}`);
  }
  if (m.group === "texture") {
    rules.push(`.osrs-texture-${m.name} {
  background-image: var(${varName(m)});
  background-size: ${px(m.width)} ${px(m.height)};
  background-repeat: repeat;
}`);
  }
  if (m.group === "control") {
    rules.push(`.osrs-${m.group}-${m.name} { --osrs-sprite: var(${varName(m)}); --osrs-sprite-w: ${m.width}; --osrs-sprite-h: ${m.height}; }`);
  }
}

// Inline the RuneStar fonts (CC0) so the stylesheet needs no static files.
const base = fs
  .readFileSync(path.join(THEME, "base.css"), "utf8")
  .replace(/url\("\/fonts\/osrs\/([\w-]+\.ttf)"\)/g, (_, f: string) => {
    const b64 = fs.readFileSync(path.join(ROOT, "registry/osrs/fonts", f)).toString("base64");
    return `url("data:font/ttf;base64,${b64}")`;
  });
fs.writeFileSync(
  OUT,
  `/* Generated by scripts/build-css.ts from theme/base.css — edit that file instead. */\n${base}\n` +
    `/* ---------- Generated asset variables ---------- */\n:root {\n${vars.join("\n")}\n}\n\n${rules.join("\n")}\n`,
);
console.log(`wrote ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
