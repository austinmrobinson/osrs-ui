// Demo-only NPC chatheads for the site (the search window's empty state), from the OSRS Wiki
// (CC BY-NC-SA 3.0; the art is Jagex's). Downloads to reference/chatheads (gitignored) and writes
// site/demo-data/chatheads.tsx with the same pixel-exact converter as the item icons. Not part of
// the registry.
import fs from "node:fs";
import path from "node:path";
import { readPng, toSvg } from "./lib/pixels";

const ROOT = path.resolve(import.meta.dirname, "..");
const DIR = path.join(ROOT, "reference/chatheads");
const OUT = path.join(ROOT, "site/demo-data/chatheads.tsx");
const UA = "osrs-ui-docs/0.1 (+https://github.com/austinmrobinson/osrs-ui)";

const NPCS = ["Hans"];

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const pascal = (s: string) => slug(s).replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());

fs.mkdirSync(DIR, { recursive: true });
const rows: string[] = [];
for (const name of NPCS) {
  const file = path.join(DIR, `${slug(name)}.png`);
  if (!fs.existsSync(file)) {
    const url = `https://oldschool.runescape.wiki/images/${encodeURIComponent(name.replace(/ /g, "_"))}_chathead.png`;
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`${name}: ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  const bmp = readPng(file);
  const inner = toSvg(bmp).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "").replace(/fill-opacity=/g, "fillOpacity=");
  rows.push(`export const ${pascal(name)}Chathead = createSprite("${pascal(name)}Chathead", ${bmp.width}, ${bmp.height}, <>${inner}</>);`);
}
fs.writeFileSync(
  OUT,
  `// Generated by scripts/fetch-chatheads.ts — demo-only NPC chatheads from the OSRS Wiki (CC BY-NC-SA 3.0).
import { createSprite } from "@/lib/sprite";

${rows.join("\n")}
`,
);
console.log(`${rows.length} chathead(s) -> site/demo-data/chatheads.tsx`);
